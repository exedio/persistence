package com.exedio.cope;

import static com.exedio.cope.instrument.Visibility.NONE;
import static com.exedio.cope.pattern.CompositeType.forClass;
import static com.exedio.cope.tojunit.Assert.assertFails;
import static org.junit.jupiter.api.Assertions.assertEquals;

import com.exedio.cope.instrument.WrapperType;
import com.exedio.cope.pattern.Composite;
import com.exedio.cope.pattern.CompositeField;
import org.junit.jupiter.api.Test;

public class ItemFieldBySubtypeCompositeBlockTest extends TestWithEnvironment
{
	@WrapperType(constructor=NONE, indent=2, comments=false)
	private static final class SourceComposite extends Composite
	{
		static final ItemField<Target> field = ItemField.createBySubtypeEXPERIMENTAL(Target.class);

		// TODO to be generated by instrumentor
		SourceComposite(
					@javax.annotation.Nonnull final Target field)
				throws
					com.exedio.cope.MandatoryViolationException
		{
			this(new com.exedio.cope.SetValue<?>[]{
					com.exedio.cope.SetValue.map(SourceComposite.field,field),
			});
		}

		@com.exedio.cope.instrument.Generated
		private SourceComposite(final com.exedio.cope.SetValue<?>... setValues){super(setValues);}

		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedStaticUsage"})
		@javax.annotation.Nonnull
		Target getField()
		{
			return get(SourceComposite.field);
		}

		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedStaticUsage"})
		void setField(@javax.annotation.Nonnull final Target field)
				throws
					com.exedio.cope.MandatoryViolationException
		{
			set(SourceComposite.field,field);
		}

		@com.exedio.cope.instrument.Generated
		@java.io.Serial
		private static final long serialVersionUID = 1l;
	}

	@WrapperType(indent=2, comments=false)
	private static final class SourceItem extends Item
	{
		static final CompositeField<SourceComposite> field = CompositeField.create(SourceComposite.class);

		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedInnerClassAccess"})
		private SourceItem(
					@javax.annotation.Nonnull final SourceComposite field)
				throws
					com.exedio.cope.MandatoryViolationException
		{
			this(new com.exedio.cope.SetValue<?>[]{
				com.exedio.cope.SetValue.map(SourceItem.field,field),
			});
		}

		@com.exedio.cope.instrument.Generated
		private SourceItem(final com.exedio.cope.SetValue<?>... setValues){super(setValues);}

		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedStaticUsage"})
		@javax.annotation.Nonnull
		SourceComposite getField()
		{
			return SourceItem.field.get(this);
		}

		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedStaticUsage"})
		void setField(@javax.annotation.Nonnull final SourceComposite field)
				throws
					com.exedio.cope.MandatoryViolationException
		{
			SourceItem.field.set(this,field);
		}

		@com.exedio.cope.instrument.Generated
		@java.io.Serial
		private static final long serialVersionUID = 1l;

		@com.exedio.cope.instrument.Generated
		private static final com.exedio.cope.Type<SourceItem> TYPE = com.exedio.cope.TypesBound.newType(SourceItem.class,SourceItem::new);

		@com.exedio.cope.instrument.Generated
		private SourceItem(final com.exedio.cope.ActivationParameters ap){super(ap);}
	}

	@WrapperType(constructor=NONE, indent=2, comments=false)
	private abstract static class Target extends Item // TODO should be an interface, once Item itself is an interface
	{
		// MUST NOT define any fields or non-abstract methods, otherwise it cannot be transferred into an interface

		@com.exedio.cope.instrument.Generated
		protected Target(final com.exedio.cope.SetValue<?>... setValues){super(setValues);}

		@com.exedio.cope.instrument.Generated
		@java.io.Serial
		private static final long serialVersionUID = 2l;

		@com.exedio.cope.instrument.Generated
		private static final com.exedio.cope.Type<Target> TYPE = com.exedio.cope.TypesBound.newTypeAbstract(Target.class);

		@com.exedio.cope.instrument.Generated
		protected Target(final com.exedio.cope.ActivationParameters ap){super(ap);}
	}

	// -------------------------------------------------------------------------------------
	// Border between framework and project
	// TargetImpl must not be mentioned above, but only below this border.
	// -------------------------------------------------------------------------------------

	@WrapperType(indent=2, comments=false)
	private static final class TargetImpl extends Target
	{
		@com.exedio.cope.instrument.Generated
		@java.lang.SuppressWarnings({"RedundantSuppression","TypeParameterExtendsFinalClass","UnnecessarilyQualifiedInnerClassAccess"})
		private TargetImpl()
		{
			this(com.exedio.cope.SetValue.EMPTY_ARRAY);
		}

		@com.exedio.cope.instrument.Generated
		private TargetImpl(final com.exedio.cope.SetValue<?>... setValues){super(setValues);}

		@com.exedio.cope.instrument.Generated
		@java.io.Serial
		private static final long serialVersionUID = 1l;

		@com.exedio.cope.instrument.Generated
		private static final com.exedio.cope.Type<TargetImpl> TYPE = com.exedio.cope.TypesBound.newType(TargetImpl.class,TargetImpl::new);

		@com.exedio.cope.instrument.Generated
		private TargetImpl(final com.exedio.cope.ActivationParameters ap){super(ap);}
	}

	private static final Model MODEL = new Model(SourceItem.TYPE, Target.TYPE, TargetImpl.TYPE);

	public ItemFieldBySubtypeCompositeBlockTest()
	{
		super(MODEL);
	}

	@Test void test()
	{
		assertEquals("com.exedio.cope.ItemField$DummyItemForCreateBySubtype", SourceComposite.field.getValueClass().getName()); // TODO should be TargetImpl.class
		//noinspection Convert2MethodRef
		assertFails(
				() -> SourceComposite.field.getValueType(), // TODO should work
				IllegalArgumentException.class,
				"createBySubtypeEXPERIMENTAL: no type assignable to " + Target.class.getName());

		assertEquals(TargetImpl.class, SourceItem.field.of(SourceComposite.field).getValueClass());
		assertEquals(TargetImpl.TYPE, SourceItem.field.of(SourceComposite.field).getValueType());

		assertEquals(SourceComposite.class, SourceItem.field.getValueClass());
		assertEquals(forClass(SourceComposite.class), SourceItem.field.getValueType());

		final var target = new TargetImpl();
		assertFails(
				() -> new SourceComposite(target), // TODO should work
				ClassCastException.class,
				"expected a com.exedio.cope.ItemField$DummyItemForCreateBySubtype, " +
				"but was a " + TargetImpl.class.getName() + " " +
				"for " + SourceComposite.field + ".");
	}
}
